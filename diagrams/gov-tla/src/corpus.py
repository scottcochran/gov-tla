"""Build-time reads of the gov-tla corpus: results files, row lists, proof results, the README's summary table.

Every reader parses strictly and raises on anything it does not expect, so a diagram that draws from a file fails
to build (the generator prints ERROR) when the file changes shape, the way a gate fails.

The results file each module's diagrams draw is NAMED here, never chosen as "the newest matching a pattern": a new
results file changes no diagram until this table is moved on purpose. A1 compares each named file with the newest
committed one (scripts/compare_results.py's rule) and with the current specs' sha256, and fails if either moved.
"""
import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[3]

# Module order is the README's (## Modules, and its summary table).
MODULES = ["Constitution", "Judiciary", "Executive", "Government", "Elections", "SenateRules"]

# The results drawn, per module: (TLC results, TLAPS proof results). Move one only together with an amendment.
RESULTS = {
    "Constitution": ("results/Constitution-results-2026.11.18.txt", "results/Constitution-proof-results-2026.11.18.txt"),
    "Judiciary":    ("results/Judiciary-results-2026.11.09.txt", "results/Judiciary-proof-results-2026.11.17.txt"),
    "Executive":    ("results/Executive-results-2026.11.16.txt", "results/Executive-proof-results-2026.11.17.txt"),
    "Government":   ("results/Government-results-2026.11.16.txt", "results/Government-proof-results-2026.11.17.txt"),
    "Elections":    ("results/Elections-results-2026.11.16.txt", "results/Elections-proof-results-2026.11.17.txt"),
    "SenateRules":  ("results/SenateRules-results-2026.11.19b.txt", "results/SenateRules-proof-results-2026.11.19b.txt"),
}


class CorpusError(Exception):
    """A file a diagram reads is missing, or not the shape the diagram expects."""


def path(rel):
    p = ROOT / rel
    if not p.is_file():
        raise CorpusError(f"missing {rel}")
    return p


def read(rel):
    return path(rel).read_text(encoding="utf-8")


def sha256(rel):
    return hashlib.sha256(path(rel).read_bytes()).hexdigest()


def newest(kind, module):
    """scripts/compare_results.py's rule: YYYY.MM.DD sorts by date, a letter suffix after the file it follows."""
    pat = f"{module}-results-*.txt" if kind == "tlc" else f"{module}-proof-results-*.txt"
    files = sorted((ROOT / "results").glob(pat))
    if not files:
        raise CorpusError(f"no results/{pat}")
    return f"results/{files[-1].name}"


def _need(cond, rel, what):
    if not cond:
        raise CorpusError(f"{rel}: {what}")


# ---------------------------------------------------------------------------------------------- TLC results
_ROW = re.compile(r"^([a-z0-9][a-z0-9-]*) \| Mut=(\S+) \| (\S+)((?: \S+=\S+)*) \| "
                  r"((?:PROPERTY |DEADLOCK |SIMULATE )?\S+(?: \([^)]*\))?) \| "
                  r"(HOLDS|COUNTEREXAMPLE|DEADLOCK|NO-ERROR-SAMPLED|ERROR) \| "
                  r"(\d+ distinct states|\d+ states checked|count not recorded) \| (as expected|NOT as expected)$")
_SUMMARY = re.compile(r"^(\d+) rows: (\d+) as expected, (\d+) not, (\d+) ERROR$")


def tlc_results(rel):
    """A results file written by scripts/tlc_rows.py. Returns a dict:
    title, date, checker, modules {file: sha256}, rows_file, rows_sha, constants, config (list), expected, flags,
    words, rows [dict(name, mut, spec, overrides, kind, prop, extra, verdict, states, sampled, ok)], total,
    as_expected, not, error.
    kind is "INVARIANT", "PROPERTY", "DEADLOCK" or "SIMULATE" (a sample, never a check: NO-ERROR-SAMPLED).
    extra is a SIMULATE row's parenthesis (depth, traces, seed). sampled is True for "<n> states checked"."""
    lines = read(rel).splitlines()
    _need(lines and lines[0].startswith("gov-tla - "), rel, "line 1 is not 'gov-tla - <Module>.tla - <title>'")
    out = {"title": lines[0][len("gov-tla - "):], "config": [], "rows": []}
    m = re.match(r"^TLC results (\d{4}\.\d{2}\.\d{2}), generated by scripts/tlc_rows.py", lines[1])
    _need(m, rel, "line 2 is not 'TLC results <date>, generated by scripts/tlc_rows.py ...'")
    out["date"] = m.group(1)
    head = {}
    i = 2
    while i < len(lines) and lines[i].strip():
        k, sep, v = lines[i].partition(": ")
        _need(sep, rel, f"header line {i + 1} has no 'Key: value'")
        if k == "Config":
            out["config"].append(v)
        else:
            _need(k not in head, rel, f"header {k} twice")
            head[k] = v
        i += 1
    for k in ("Checker", "Modules", "Rows", "Constants", "Expected", "Flags", "Words"):
        _need(k in head, rel, f"no {k}: line")
    out["checker"], out["constants"], out["expected"] = head["Checker"], head["Constants"], head["Expected"]
    out["flags"], out["words"] = head["Flags"], head["Words"]
    toks = head["Modules"].split()
    _need(len(toks) % 2 == 0 and all(re.fullmatch(r"[0-9a-f]{64}", t) for t in toks[1::2]), rel, "bad Modules: line")
    out["modules"] = dict(zip(toks[::2], toks[1::2]))
    m = re.fullmatch(r"(rows/\S+) sha256 ([0-9a-f]{64})", head["Rows"])
    _need(m, rel, "bad Rows: line")
    out["rows_file"], out["rows_sha"] = m.group(1), m.group(2)
    summary = None
    for ln in lines[i:]:
        if not ln.strip():
            continue
        s = _SUMMARY.match(ln)
        if s:
            _need(summary is None, rel, "two summary lines")
            summary = tuple(int(g) for g in s.groups())
            continue
        r = _ROW.match(ln)
        _need(r, rel, f"row does not parse: {ln[:90]!r}")
        _need(summary is None, rel, "a row after the summary line")
        prop = r.group(5)
        kind, extra = "INVARIANT", None
        for k in ("PROPERTY", "DEADLOCK", "SIMULATE"):
            if prop.startswith(k + " "):
                kind, prop = k, prop[len(k) + 1:]
        if " (" in prop:
            prop, extra = prop.split(" (", 1)
            extra = extra.rstrip(")")
        st = r.group(7)
        out["rows"].append({
            "name": r.group(1), "mut": r.group(2), "spec": r.group(3),
            "overrides": r.group(4).split(), "kind": kind, "prop": prop, "verdict": r.group(6),
            "states": int(st.split()[0]) if st[0].isdigit() else None, "sampled": "checked" in st,
            "extra": extra, "ok": r.group(8) == "as expected"})
    _need(summary is not None, rel, "no '<n> rows: ...' summary line")
    out["total"], out["as_expected"], out["not"], out["error"] = summary
    _need(out["total"] == len(out["rows"]), rel, f"summary says {out['total']} rows, file has {len(out['rows'])}")
    _need(out["as_expected"] == sum(r["ok"] for r in out["rows"]), rel, "summary's as-expected count is wrong")
    names = [r["name"] for r in out["rows"]]
    _need(len(set(names)) == len(names), rel, "a row name twice")
    return out


def mutations(res):
    """The module's mutations in the order the results file first runs them (Mut=none excluded)."""
    seen = []
    for r in res["rows"]:
        if r["mut"] != "none" and r["mut"] not in seen:
            seen.append(r["mut"])
    return seen


def witnesses(res):
    """The Never... witness rows: unmutated rows (INVARIANT or PROPERTY) on a property named Never..."""
    return [r for r in res["rows"] if r["mut"] == "none" and r["prop"].startswith("Never")]


def matrix(res, spec="Spec"):
    """Mutation x property verdicts over INVARIANT rows of `spec`, excluding witnesses.
    Returns (muts, props, cells) with cells[(mut, prop)] = set of verdicts (a property can be run more than once
    under one mutation at different constants). muts starts with "none"."""
    muts = ["none"] + mutations(res)
    props, cells = [], {}
    for r in res["rows"]:
        if r["kind"] != "INVARIANT" or r["spec"] != spec or r["prop"].startswith("Never"):
            continue
        if r["prop"] not in props:
            props.append(r["prop"])
        cells.setdefault((r["mut"], r["prop"]), set()).add(r["verdict"])
    return muts, props, cells


# ---------------------------------------------------------------------------------------------- proof results
_THM = re.compile(r"^THEOREM (\w+) == (?:ASSUME (.+?) PROVE )?(.+)$")


def proof_results(rel):
    """A results file written by scripts/proof_results.py. Returns a dict: title, date, command, modules,
    prover, backends, tlc_file, tlc_sha, words, theorems [dict(name, assume [str], prove)], lemmas [str],
    obligations (int)."""
    text = read(rel)
    lines = text.splitlines()
    m = re.match(r"^gov-tla - (\w+)_proof\.tla, TLAPS proof results (\d{4}\.\d{2}\.\d{2})$", lines[0])
    _need(m, rel, "line 1 is not 'gov-tla - <Module>_proof.tla, TLAPS proof results <date>'")
    out = {"module": m.group(1), "date": m.group(2), "theorems": [], "lemmas": []}
    head = {}
    for ln in lines[1:]:
        if not ln.strip():
            break
        if ln.startswith("Generated by scripts/proof_results.py"):
            out["command"] = ln.split("Command: ", 1)[1] if "Command: " in ln else ""
            continue
        k, sep, v = ln.partition(": ")
        _need(sep, rel, f"header line has no 'Key: value': {ln[:60]!r}")
        head[k] = v
    for k in ("Modules", "Prover", "Backends", "Words"):
        _need(k in head, rel, f"no {k}: line")
    toks = head["Modules"].split()
    out["modules"] = dict(zip(toks[::2], toks[1::2]))
    out["prover"], out["backends"], out["words"] = head["Prover"], head["Backends"], head["Words"]
    tlc = [v for k, v in head.items() if k.startswith("TLC results")]
    out["tlc_file"] = out["tlc_sha"] = None
    if tlc:
        m = re.fullmatch(r"(results/\S+) sha256 ([0-9a-f]{64})", tlc[0])
        _need(m, rel, "bad 'TLC results ...:' line")
        out["tlc_file"], out["tlc_sha"] = m.group(1), m.group(2)
    # The theorem and lemma block is printed twice (after the header and again at the end); read the first.
    for ln in lines:
        t = _THM.match(ln)
        if t:
            if any(x["name"] == t.group(1) for x in out["theorems"]):
                break
            out["theorems"].append({"name": t.group(1),
                                    "assume": [a.strip() for a in t.group(2).split(",")] if t.group(2) else [],
                                    "prove": t.group(3)})
    lem = re.search(r"^LEMMAS \((\d+)\): (.+)$", text, re.M)
    _need(lem, rel, "no 'LEMMAS (n): ...' line")
    out["lemmas"] = [x.strip() for x in lem.group(2).split(",")]
    _need(len(out["lemmas"]) == int(lem.group(1)), rel, "LEMMAS count does not match the list")
    res = re.findall(r"^Result: All (\d+) obligations proved\.$", text, re.M)
    _need(res and len(set(res)) == 1, rel, "no single 'Result: All <n> obligations proved.' line")
    out["obligations"] = int(res[0])
    _need(out["theorems"], rel, "no THEOREM lines")
    return out


# ---------------------------------------------------------------------------------------------- the README
_SUMHEAD = "| Module | TLC rows (all as expected) | Mutations | Witnesses | Proof obligations (all proved) |"


def readme_summary():
    """The README's summary table (## How the specs are written and checked). Returns
    {module: dict(rows, mutations, witnesses, obligations)}, in table order."""
    lines = read("README.md").splitlines()
    _need(_SUMHEAD in lines, "README.md", "summary table header not found")
    i = lines.index(_SUMHEAD) + 2
    out = {}
    while i < len(lines) and lines[i].startswith("| `"):
        cells = [c.strip() for c in lines[i].strip("|").split("|")]
        m = re.fullmatch(r"`(\w+)\.tla`", cells[0])
        _need(m and len(cells) == 5, "README.md", f"summary row does not parse: {lines[i]!r}")
        n = [int(c.replace(",", "")) for c in cells[1:]]
        out[m.group(1)] = dict(rows=n[0], mutations=n[1], witnesses=n[2], obligations=n[3])
        i += 1
    _need(list(out) == MODULES, "README.md", f"summary table modules {list(out)} are not {MODULES}")
    return out


def proof_gaps():
    """PROOF-GAPS.txt: modules with no proof module. Returns {module: reason}."""
    out = {}
    for ln in read("PROOF-GAPS.txt").splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        k, sep, v = ln.partition(": ")
        _need(sep, "PROOF-GAPS.txt", f"line is not '<Module>: <reason>': {ln!r}")
        out[k] = v
    return out
